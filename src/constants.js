export const getWeatherInfo = (code) => {
  const numericCode = Number(code)
  const rawValue = WEATHER_CODES[numericCode]

  if (!rawValue) {
    return { description: 'Невідомо', emoji: '❔' }
  }

  const parts = rawValue.split(' ')
  const emoji = parts[parts.length - 1]
  const description = parts.slice(0, -1).join(' ')

  return {
    description: description || 'Невідомо',
    emoji: emoji || '❔',
  }
}
